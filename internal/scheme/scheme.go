// Package scheme 은 이 편집기 전체에서 통용되는 개념들이다.
//
// **여기 있는 것은 겹 사이를 오가는 자료다.** 키가 MotionRange 를 지어 글에 건네고, 글이 그
// Cursor 로 자르고, 창이 그리며 Cell 로 옮긴다. 누구의 것도 아니고 오가기만 한다.
//
// 무엇이 여기 오는지는 「지금 누가 부르나」가 아니라 **「이 말이 어디까지 통용되나」**로
// 가른다 (ADR-0122).
//
//   - **오가는 자료.** 값만 들고 아무 일도 하지 않는다. 여기 온다
//   - **한 겹의 상태.** `viewTop`(이 창이 어디부터 그리나)·`selection`·`edit` 은 메서드가
//     없어도 오가지 않는다. 자기 겹에 남는다
//   - **뜻을 아는 물건.** `register` 는 「몇 자인가」·「무엇을 알릴까」를 스스로 안다. 값만 든
//     것이 아니라 자기 겹에 남는다
//
// 「메서드가 없다」는 필요조건이고 「겹을 넘나든다」가 그 위에 있다.
//
// **이 잣대는 패키지 경계가 정해지기 전에도 쓸 수 있다.** core 를 어디로 가르든 오가는
// 자료는 그 선을 넘고 상태는 자기 겹에 남는다. Cell 이 지금 한 자리에서만 쓰이는데도 여기
// 있는 것은 **화면 칸이라는 개념 자체가 공용**이기 때문이다.
//
// **동작을 두지 않는다.** 여기에 메서드가 붙기 시작하면 그것은 이미 「뜻을 아는 물건」이고,
// 그 뜻은 어느 한 겹의 것이라 이 패키지가 그 겹을 알게 된다. `internal/lines` 가 그 길로
// 갔다가 물렸다 (ADR-0119).
package scheme

// Cursor 는 파일 안의 자리다.
//
// **Col 은 화면 칸이 아니라 byte offset 이다.** 이 저장소에는 `col` 이라는 낱말이 두 단위로
// 있어서 type 으로 가른다 — 여기는 줄 안의 byte 이고, 화면에 그려진 칸은 Cell 이다.
// 그냥 `int` 둘이던 때는 바꿔 넣어도 컴파일이 되었다 (ADR-0122).
type Cursor struct {
	Line int // 파일의 몇 번째 줄인가. 논리 줄이다
	Col  int // 그 줄 안의 byte offset
}

// Cell 은 화면에 그려진 자리다. 터미널 셀 격자의 칸이라 둘 다 화면 칸으로 센다.
//
// X, Y 로 세는 것은 받는 쪽(`tea.NewCursor`) 의 어휘이기도 하고, `Col` 을 쓰면 Cursor 의
// byte offset 과 같은 낱말이 되어 다시 헷갈린다.
type Cell struct {
	X int // 왼쪽에서 몇 번째 칸
	Y int // 위에서 몇 번째 행
}

// MotionRange 는 operator 가 잡은 범위다. `d` 와 `y` 가 같이 쓴다.
//
// 글자 단위면 Start 부터 End **앞까지** 이고, 줄 단위면 [Start.Line, End.Line] 줄 전체다.
//
// **만드는 곳이 넷이다** — motion.go 의 span, viewport-selection.go 의 visual,
// command-range.go 의 줄 범위, cat.go. 받는 곳은 글과 창의 `*Range` 들이다.
//
// **줄 단위여도 칸을 담는다.** 고치는 자리는 그 칸을 보지 않는다 — 줄 단위 연산은 전부
// Linewise 로 갈라 줄 전체를 쓴다(`deleteLines`·`changeCaseRange`·`selectionOn`·`catLines`).
// 담는 까닭은 **복사가 커서를 범위의 시작으로 옮기기 때문**이다. `yk` 는 칸을 지키고 `ygg` 는
// 첫 비공백으로 가는데, 그 칸이 범위에 없으면 어디서도 만들어 낼 수 없다.
//
// 그래서 이 struct 는 좌표 다섯뿐이고 그 밖의 것을 싣지 않는다. 「범위를 잡은 손이 커서를 둔
// 자리」를 따로 들고 다니던 두 필드가 있었는데, 재 보니 **그것이 늘 범위의 시작이었다** —
// span 이 커서 자리와 이동이 닿은 자리로 범위를 짓기 때문이다(charSpan·lineSpan).
// 커서를 옮길지는 부르는 쪽이 정한다(ADR-0100 §5).
type MotionRange struct {
	Start, End Cursor
	Linewise   bool
}
