//
// core 밖에 있는 것은 여기 든 것이 데이터일 뿐이기 때문이다 — 글을 고치려고 편집기 코드를
// 열 이유가 없다. 쓰는 규칙은 저쪽에 남는다(tip 을 고르는 core/tip.go 의 fitTip,
// 유니코드를 훑는 core/symbol.go 의 indexSymbols).
//
// **경계는 코드가 붙어 있는지다.** 팔레트 명령 표(core/palette.go 의 paletteCommands) 는
// 항목마다 실행할 함수를 들고 있어서 여기 오지 않는다 — 그것은 표가 아니라 코드다(ADR-0061).
